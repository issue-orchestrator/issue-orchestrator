"""Externally authored PRs in an integration effort: the vocabulary (#9499).

Work done off to the side - by the coordinator, the operator or another tool -
enters io as an ordinary PR, and io owns everything downstream: review, the
merge into the effort's branch, the delivery. The PR is the splice point.

* **The effort.** An integration effort is integration mode's branch
  (#8144); an issue belongs to it when it carries :func:`effort_label`
  (``integrate:<branch>``).
* **Provenance.** io's own PRs carry :data:`ORCHESTRATOR_PR_MARKER` in their
  body. Any other PR is external. One the effort governs - adopted, or into
  the effort branch (:func:`effort_governs`) - io reviews, reworks, updates
  or merges only while it is ADOPTED (it carries
  :data:`ORIGIN_EXTERNAL_LABEL`, which also lets the tech lead, the improver
  and an evaluation separate adopted work from io's own) and still ADMITTED;
  an external PR into another base that was never adopted is not the
  effort's business. Once adopted, the label decides: a body that later
  carries io's marker does not make the PR io's own.
* **THE admission rule.** :func:`judge_external_pull_request` is the one
  decision every boundary asks, on :class:`ExternalPullRequestFacts` it reads
  itself: discovery, the applier's re-check before each adoption, refusal,
  return-to-review, update or merge write, and the merge/update/rework routing
  (through :func:`merge_refusal`), and the review and rework launches
  (:class:`LaunchAdmission`). A PR is admitted while it is open, targets
  the effort branch, references exactly one issue (:class:`IssueLink`) that is open, in the
  engine's complete scope, labelled for the effort and reworkable (an agent
  label), and io holds no other attempt at that issue (:class:`IoCustody`).
* **Fail closed.** A PR into the effort branch that is not admitted, and a PR
  for an issue in the effort that targets another base, is
  :class:`AdoptionRefusal`-refused: never merged, and reported once per
  refusal identity (reason, issue, bases, detail - :func:`refusal_marker`),
  acknowledged only once that report is seen on the PR.
* **Convergent writes.** Each multi-label write is ordered so that every
  prefix of it - a write that failed part-way - is a state the owner plans
  the same write from again (:class:`PullRequestLabelWrites`).
* **Reviewed-head custody.** An approval binds to the exact head io's
  reviewer reviewed, not to the ``code-reviewed`` label (which survives a
  push): io's approval of an adopted PR leaves a
  :func:`reviewed_head_receipt` on the PR, written under io's own credential,
  and the merge gate requires one for the PR's current head. A head without
  one - pushed after the approval, pushed while the review was completing, or
  io's own mechanical update onto the effort tip - is not merged; it goes back
  to io's review (:class:`ReturnExternalPullRequestToReview`).

Pure values: the owner (:mod:`~..control.external_pr_adoption`) reads GitHub
and decides; the steps here are facts its planner turns into actions.
"""

from __future__ import annotations

import hashlib
import re
from collections.abc import Iterable, Mapping
from dataclasses import dataclass, field
from enum import StrEnum

from .session_kind import SessionKind

#: Marker used in PR bodies to identify orchestrator-generated PRs.
ORCHESTRATOR_PR_MARKER = "Generated by issue-orchestrator"

#: The PR label naming adopted work's origin (one spelling, never prefixed).
ORIGIN_EXTERNAL_LABEL = "origin:external"

#: An issue in the integration effort of branch ``B`` carries ``integrate:B``.
EFFORT_LABEL_PREFIX = "integrate:"

_REFUSAL_MARKER_PREFIX = "<!-- io:external-pr-refused reason="
_SHA = re.compile(r"[0-9a-f]{40}")


def effort_label(branch: str) -> str:
    """The issue label that puts an issue in the effort integrating on *branch*."""
    if not branch:
        raise ValueError("an integration effort names its branch")
    return f"{EFFORT_LABEL_PREFIX}{branch}"


def io_authored(body: str | None) -> bool:
    """Whether a PR body is one io wrote for its own work."""
    return ORCHESTRATOR_PR_MARKER in (body or "")


def io_owned_pr(body: str | None, labels: Iterable[str]) -> bool:
    """io's own PR: its marker, and never adopted (the origin label decides once it is on)."""
    return io_authored(body) and ORIGIN_EXTERNAL_LABEL not in labels


def in_effort(branch: str, issue_labels: Iterable[str]) -> bool:
    """Whether an issue with *issue_labels* belongs to the effort integrating on *branch*."""
    return effort_label(branch) in issue_labels


# -- the facts THE admission rule judges -------------------------------------------


@dataclass(frozen=True)
class IssueLink:
    """The issues a PR's branch and body reference: none, exactly one, or several.

    Only exactly one is a reference io can act on: a PR that names several is
    ambiguous, whichever one a lane would pick first.
    """

    issues: frozenset[int]

    @property
    def issue(self) -> int | None:
        """The one issue referenced; None for none or several."""
        return next(iter(self.issues)) if len(self.issues) == 1 else None

    @property
    def ambiguous(self) -> bool:
        return len(self.issues) > 1

    def describe(self) -> str:
        numbers = [f"#{number}" for number in sorted(self.issues)]
        if not numbers:
            return "no issue"
        if len(numbers) == 1:
            return f"issue {numbers[0]}"
        return f"issues {', '.join(numbers[:-1])} and {numbers[-1]}"


@dataclass(frozen=True)
class PullRequestFacts:
    """One PR, as GitHub reports it now."""

    number: int
    open: bool
    draft: bool
    body: str
    branch: str
    base_branch: str | None
    labels: frozenset[str]
    #: Every issue the PR's branch and body reference (with the one every lane
    #: resolves it to, should that differ).
    link: IssueLink

    @property
    def linked_issue(self) -> int | None:
        """The one issue the PR references; None when it names none, or several."""
        return self.link.issue

    @property
    def adopted(self) -> bool:
        return ORIGIN_EXTERNAL_LABEL in self.labels

    @property
    def io_owned(self) -> bool:
        """io's own PR: its marker, and never adopted (the label decides once it is on)."""
        return io_owned_pr(self.body, self.labels)


@dataclass(frozen=True)
class LinkedIssueFacts:
    """The issue a PR references, as GitHub reports it now."""

    number: int
    #: Why the issue is outside the engine's complete scope (closed, milestone,
    #: label filters, single-issue scope); None when it is inside.
    scope_gap: str | None
    labels: frozenset[str]
    #: The issue's agent label (``agent:<name>``), if it carries one.
    agent_type: str | None
    #: Whether that agent is one this engine runs: only then can io rework the PR.
    agent_configured: bool

    def __post_init__(self) -> None:
        if self.agent_configured and self.agent_type is None:
            raise ValueError(f"issue #{self.number} has no agent label, so no configured agent")


@dataclass(frozen=True)
class IoCustody:
    """io's own hold on one issue, as the boundary asking reads it."""

    #: The branch an io session or worktree works the issue on, if any.
    working_branch: str | None
    #: io's own PRs for the issue (open, or published and awaiting merge) and
    #: every adopted one: two attempts never share an issue.
    pull_requests: frozenset[int]

    def conflict(self, issue_number: int, pr: PullRequestFacts) -> str | None:
        """io's other attempt at *issue_number*, when *pr* is not it; None when there is none."""
        if self.working_branch and self.working_branch != pr.branch:
            return f"io is working issue #{issue_number} on its own branch `{self.working_branch}`"
        others = sorted(self.pull_requests - {pr.number})
        if others:
            return f"PR #{others[0]} is already an attempt at issue #{issue_number} that io owns"
        return None


@dataclass(frozen=True)
class ExternalPullRequestFacts:
    """Everything THE admission rule reads about one PR."""

    pr: PullRequestFacts
    #: The referenced issue, read whenever the PR references one.
    issue: LinkedIssueFacts | None
    custody: IoCustody

    def __post_init__(self) -> None:
        read = None if self.issue is None else self.issue.number
        if read != self.pr.linked_issue:
            raise ValueError(f"PR #{self.pr.number} references issue {self.pr.linked_issue}, facts read {read}")


class AdoptionRefusal(StrEnum):
    """Why an external PR is not admitted. Each one is reported, none is merged."""

    #: It targets the effort branch but references no issue.
    NO_ISSUE_REFERENCE = "no_issue_reference"
    #: It targets the effort branch, but its issue is not (or no longer) in the effort.
    ISSUE_NOT_IN_EFFORT = "issue_not_in_effort"
    #: Its issue is in the effort, but it targets another base.
    WRONG_BASE = "wrong_base"
    #: Its issue is in the effort, but io already holds another attempt at it.
    IO_WORK_IN_FLIGHT = "io_work_in_flight"
    #: It references several issues: io acts on a PR for exactly one.
    AMBIGUOUS_ISSUE_REFERENCE = "ambiguous_issue_reference"


class Admission(StrEnum):
    """Where one open PR stands with the effort."""

    #: Not external work in this effort: io's own, a draft, closed, the
    #: delivery PR, or into another base for an issue outside the effort.
    IGNORED = "ignored"
    #: External, into the effort branch, eligible, not adopted yet.
    ADOPTABLE = "adoptable"
    #: Adopted and still eligible: io's lanes may act on it.
    ADMITTED = "admitted"
    #: External work io will not adopt or act on (``refusal`` says why).
    REFUSED = "refused"


@dataclass(frozen=True)
class ExternalAdmission:
    """THE admission rule's verdict on one PR."""

    admission: Admission
    #: The issue the PR references (None when it references none).
    issue_number: int | None
    refusal: AdoptionRefusal | None = None
    detail: str = ""

    def __post_init__(self) -> None:
        if (self.refusal is None) is (self.admission is Admission.REFUSED):
            raise ValueError("a refusal names its reason, and only a refusal does")


def issue_gap(branch: str, issue: LinkedIssueFacts) -> str | None:
    """Why *issue* is not (or no longer) in the effort; None when it is."""
    if issue.scope_gap is not None:
        return f"issue #{issue.number} is not open in this engine's scope ({issue.scope_gap})"
    if not in_effort(branch, issue.labels):
        return f"issue #{issue.number} is not labelled `{effort_label(branch)}`"
    if issue.agent_type is None:
        return f"issue #{issue.number} has no agent label, so io could not rework it"
    if not issue.agent_configured:
        return (f"issue #{issue.number}'s agent label `{issue.agent_type}` names no agent this engine"
                " runs, so io could not rework it")
    return None


def external_work(branch: str, pr: PullRequestFacts) -> bool:
    """Whether *pr* is external work at all (before its issue is read): open,
    ready, not io's own, and not the effort's delivery PR."""
    return pr.open and not pr.draft and not pr.io_owned and pr.branch != branch


def effort_governs(branch: str, pr: PullRequestFacts) -> bool:
    """Whether io may act on *pr* only as THE admission rule allows: it is not
    io's own, and it is adopted or targets the effort branch. Any other PR is
    not the effort's business, and its lanes run as without the effort."""
    return not pr.io_owned and (pr.adopted or pr.base_branch == branch)


def judge_external_pull_request(branch: str, facts: ExternalPullRequestFacts) -> ExternalAdmission:
    """THE admission rule for one PR and the effort integrating on *branch*."""
    pr, issue = facts.pr, facts.issue
    if not external_work(branch, pr):
        return ExternalAdmission(Admission.IGNORED, pr.linked_issue)
    if pr.link.ambiguous:
        return _refused(None, AdoptionRefusal.AMBIGUOUS_ISSUE_REFERENCE,
                        f"it references {pr.link.describe()}; io adopts a PR for exactly one issue")
    if pr.base_branch != branch:
        if issue is not None and in_effort(branch, issue.labels) and issue.scope_gap is None:
            return _refused(issue.number, AdoptionRefusal.WRONG_BASE,
                            f"it targets `{pr.base_branch}`, but issue #{issue.number} integrates on `{branch}`")
        return ExternalAdmission(Admission.IGNORED, pr.linked_issue)
    if issue is None:
        return _refused(None, AdoptionRefusal.NO_ISSUE_REFERENCE, f"it targets `{branch}` but references no issue")
    gap = issue_gap(branch, issue)
    if gap is not None:
        return _refused(issue.number, AdoptionRefusal.ISSUE_NOT_IN_EFFORT, gap)
    conflict = facts.custody.conflict(issue.number, pr)
    if conflict is not None:
        return _refused(issue.number, AdoptionRefusal.IO_WORK_IN_FLIGHT, conflict)
    return ExternalAdmission(Admission.ADMITTED if pr.adopted else Admission.ADOPTABLE, issue.number)


def _refused(issue_number: int | None, refusal: AdoptionRefusal, detail: str) -> ExternalAdmission:
    return ExternalAdmission(Admission.REFUSED, issue_number, refusal=refusal, detail=detail)


def merge_refusal(
    branch: str, pr: PullRequestFacts, *, issue: LinkedIssueFacts, custody: IoCustody,
) -> str | None:
    """Why io may not rework, update or merge *pr* as *issue*'s PR; None when it may.

    io's own PR is its lanes' to act on. An external one must be ADMITTED by
    THE admission rule for exactly *issue*: an edit that drops the reference,
    or points it at another issue, takes it out of every lane.
    """
    if pr.io_owned:
        return None
    if pr.linked_issue != issue.number:
        return f"PR #{pr.number} references {pr.link.describe()}, not issue #{issue.number}"
    verdict = judge_external_pull_request(branch, ExternalPullRequestFacts(pr=pr, issue=issue, custody=custody))
    if verdict.admission is Admission.ADMITTED:
        return None
    if verdict.admission is Admission.REFUSED:
        return verdict.detail
    return f"PR #{pr.number} is not an adopted PR io may act on ({verdict.admission.value})"


class LaunchVerdict(StrEnum):
    """Whether a queued review or rework of a PR may launch, as the effort sees it."""

    ADMITTED = "admitted"
    #: The PR is no longer admitted: the queued work is withdrawn, not retried.
    WITHDRAWN = "withdrawn"
    #: The facts could not be read: the launch fails and is retried.
    UNREADABLE = "unreadable"


@dataclass(frozen=True)
class LaunchAuthority:
    """The authority queued work on a PR the integration effort governs was
    admitted under: the effort, and EXACTLY the PR, issue and agent it was
    admitted for. Built once, when the work is queued, persisted with it, and
    never re-derived: the launch is judged against it unchanged."""

    effort: str
    issue_number: int
    pr_number: int
    #: The agent the work runs as (a rework) or whose reviewer reviews it.
    agent: str

    def __post_init__(self) -> None:
        if not self.effort or not self.agent:
            raise ValueError("a launch authority names its effort and its agent")


@dataclass(frozen=True)
class LaunchAdmission:
    """THE admission rule's answer when review or rework of a PR is queued or launched."""

    verdict: LaunchVerdict
    reason: str = ""
    #: When an effort governs the admitted work: the complete authority it is
    #: queued under. None when no effort governs it (or it was not admitted).
    authority: LaunchAuthority | None = None

    def __post_init__(self) -> None:
        if (self.verdict is LaunchVerdict.ADMITTED) is bool(self.reason):
            raise ValueError("a refused launch says why, and an admitted one does not")
        if self.authority is not None and self.verdict is not LaunchVerdict.ADMITTED:
            raise ValueError("only admitted work carries an authority")


LAUNCH_ADMITTED = LaunchAdmission(LaunchVerdict.ADMITTED)


@dataclass(frozen=True)
class LaunchRequest:
    """Review or rework of a PR about to be queued or launched."""

    kind: SessionKind
    issue_number: int
    pr_number: int
    #: The authority the work was queued under; None when no effort governed
    #: it then. Once set it never lapses: the work stays governed whatever the
    #: PR's labels or base say now, and only for exactly its PR, issue and agent.
    authority: LaunchAuthority | None
    #: The agent the work names when it carries no authority.
    agent: str | None
    #: The PR was found at launch, not named by the queued work (a PR-less
    #: legacy rework): such work never acts on a PR the effort governs.
    resolved_at_launch: bool = False


def launch_refusal(
    branch: str, request: LaunchRequest, pr: PullRequestFacts, *, issue: LinkedIssueFacts, custody: IoCustody,
) -> str | None:
    """Why *request* must not launch now; None when it may.

    Governed when its queued authority OR the PR's current facts put it in
    the effort, so no mix of later edits (the origin label dropped AND the
    base changed, io's marker pasted in) erases that custody. Governed work
    launches only on exactly the PR and issue its authority names, while THE
    admission rule admits that PR for that issue, and as the agent the issue
    names now - the one it was queued for.
    """
    authority = request.authority
    if authority is None and not effort_governs(branch, pr):
        return None
    if request.resolved_at_launch:
        return (f"PR #{pr.number} was found at launch, not queued with the {request.kind.value}: io acts on a PR"
                " the effort governs only under the authority it was queued with")
    if authority is not None:
        if authority.effort != branch:
            return f"queued under the `{authority.effort}` effort, not `{branch}`"
        if (authority.pr_number, authority.issue_number) != (pr.number, issue.number):
            return (f"queued for PR #{authority.pr_number} of issue #{authority.issue_number},"
                    f" not PR #{pr.number} of issue #{issue.number}")
    if pr.linked_issue != issue.number:
        return f"PR #{pr.number} references {pr.link.describe()}, not issue #{issue.number}"
    verdict = judge_external_pull_request(branch, ExternalPullRequestFacts(pr=pr, issue=issue, custody=custody))
    if verdict.admission is not Admission.ADMITTED:
        return verdict.detail or f"PR #{pr.number} is not an adopted PR io may act on ({verdict.admission.value})"
    agent = authority.agent if authority is not None else request.agent
    if agent is not None and issue.agent_type != agent:
        return f"issue #{issue.number} names `{issue.agent_type}` now, not `{agent}` the {request.kind.value} was queued for"
    return None


def launch_authority(branch: str, pr: PullRequestFacts, issue: LinkedIssueFacts) -> LaunchAuthority | None:
    """The authority work on *pr* for *issue* is queued under when the effort
    governs it (THE admission rule having admitted it); None when it does not."""
    if not effort_governs(branch, pr):
        return None
    if issue.agent_type is None:
        raise ValueError(f"admitted issue #{issue.number} names no agent")
    return LaunchAuthority(effort=branch, issue_number=issue.number, pr_number=pr.number, agent=issue.agent_type)


# -- reviewed-head custody -----------------------------------------------------------


def reviewed_head_receipt(pr_number: int, head_sha: str) -> str:
    """The exact comment io's approval of an adopted PR leaves: one per reviewed head.

    Exact on purpose: the merge gate asks for THIS body, written under io's
    own credential, for the PR's current head - never a marker substring,
    which anyone who can comment could write.
    """
    if not _SHA.fullmatch(head_sha):
        raise ValueError(f"a reviewed head is a full commit SHA, got {head_sha!r}")
    return "\n".join([
        f"<!-- io:reviewed-head pr={pr_number} sha={head_sha} -->",
        f"issue-orchestrator's review approved this pull request at `{head_sha}`.",
        "",
        "Only that commit is approved: io merges this PR only while it is the PR's head;"
        " any other head goes back to io's review first.",
    ])


@dataclass(frozen=True)
class ReturnExternalPullRequestToReview:
    """Send an adopted PR whose head io's review never approved back to that review.

    Its approval labels were given to another head (a push after the
    approval, or io's own mechanical update onto the effort tip): they are
    removed, and the PR re-enters io's review lane.
    """

    issue_number: int
    pr_number: int
    #: The head io's review never approved; the write re-checks it is still the head.
    head_sha: str
    integration_branch: str
    #: The label io's review discovery lists PRs by.
    review_label: str


# -- adoption and refusal steps --------------------------------------------------------


_REMEDIES: dict[AdoptionRefusal, str] = {
    AdoptionRefusal.AMBIGUOUS_ISSUE_REFERENCE: (
        "Reference exactly one issue: one `Closes #N` (or `Refs #N`) in the body, and a branch name that"
        " names no other issue; the issue must carry `{label}`."
    ),
    AdoptionRefusal.NO_ISSUE_REFERENCE: (
        "Reference the issue it delivers (`Closes #N` in the body, or an `N-` branch name);"
        " the issue must carry `{label}`."
    ),
    AdoptionRefusal.ISSUE_NOT_IN_EFFORT: (
        "The issue it references must be open, in this engine's scope, labelled `{label}`"
        " and carry an agent label."
    ),
    AdoptionRefusal.WRONG_BASE: "Change its base branch to `{branch}`.",
    AdoptionRefusal.IO_WORK_IN_FLIGHT: (
        "io already holds another attempt at this issue; close one of the two attempts."
    ),
}


@dataclass(frozen=True)
class AdoptExternalPullRequest:
    """Adopt one external PR into the effort.

    The write routes it into io's own review lane - an approval io did not
    give (``code-reviewed`` or ``tech-lead-reviewed`` already on the PR) never
    stands for io's review - and marks its origin LAST, so a PR is adopted
    only once it is in the lane.
    """

    issue_number: int
    pr_number: int
    pr_url: str
    pr_title: str
    integration_branch: str
    #: The label io's review discovery lists PRs by.
    review_label: str


@dataclass(frozen=True)
class LabelWrite:
    """One PR label write."""

    label: str
    #: True adds the label; False removes it.
    add: bool


@dataclass(frozen=True)
class PullRequestLabelWrites:
    """The PR label writes of one step, IN ORDER.

    The order is the contract: a write that fails part-way leaves a prefix of
    them applied, and every prefix is a state the owner plans the same step
    from again, so the next pass converges on the whole.
    """

    writes: tuple[LabelWrite, ...]

    @staticmethod
    def of(current: Iterable[str], *steps: tuple[str, bool]) -> "PullRequestLabelWrites":
        """*steps* in order, without the ones *current* already satisfies."""
        present = frozenset(current)
        return PullRequestLabelWrites(tuple(
            LabelWrite(label, add) for label, add in steps if (label in present) is not add
        ))


def adoption_label_writes(
    current: Iterable[str], *, review_label: str, approvals: Iterable[str],
) -> PullRequestLabelWrites:
    """Nothing once adopted; otherwise drop every approval io did not give,
    enter io's review lane, and mark the origin LAST: until the origin is on,
    the PR is a candidate the next scan plans this adoption for again."""
    if ORIGIN_EXTERNAL_LABEL in frozenset(current):
        return PullRequestLabelWrites(())
    dropped = [label for label in dict.fromkeys(approvals) if label != review_label]
    return PullRequestLabelWrites.of(
        current, *((label, False) for label in dropped), (review_label, True), (ORIGIN_EXTERNAL_LABEL, True),
    )


def return_to_review_label_writes(
    current: Iterable[str], *, review_label: str, reviewed_label: str, other_approvals: Iterable[str],
) -> PullRequestLabelWrites:
    """Drop every other approval, enter io's review lane, and drop
    *reviewed_label* LAST: while it stands, the integration owner routes the
    PR and plans this return again, so a write that failed part-way never
    leaves the PR outside every lane, nor keeps a stale approval past it."""
    others = [label for label in dict.fromkeys(other_approvals) if label not in (reviewed_label, review_label)]
    return PullRequestLabelWrites.of(
        current, *((label, False) for label in others), (review_label, True), (reviewed_label, False),
    )


@dataclass(frozen=True)
class ReportRefusedExternalPullRequest:
    """Tell a refused PR, on the PR itself, why io will not adopt or merge it."""

    pr_number: int
    pr_url: str
    #: The issue the PR references; None when it references none.
    issue_number: int | None
    base_branch: str
    integration_branch: str
    refusal: AdoptionRefusal
    detail: str


def refusal_marker(step: ReportRefusedExternalPullRequest) -> str:
    """The hidden marker a refusal comment carries: one comment per refusal
    IDENTITY - reason, referenced issue, both bases and the detail - so a
    report about another issue or another cause never stands for this one."""
    identity = "\x1f".join([
        step.refusal.value, str(step.issue_number), step.base_branch, step.integration_branch, step.detail,
    ])
    digest = hashlib.sha256(identity.encode()).hexdigest()[:16]
    return f"{_REFUSAL_MARKER_PREFIX}{step.refusal.value} id={digest} -->"


def render_refusal_comment(step: ReportRefusedExternalPullRequest) -> str:
    """The comment io leaves on a PR it refused."""
    remedy = _REMEDIES[step.refusal].format(
        label=effort_label(step.integration_branch), branch=step.integration_branch,
    )
    return "\n".join([
        refusal_marker(step),
        f"issue-orchestrator will not adopt this pull request into the `{step.integration_branch}`"
        " integration effort, and will never merge it.",
        "",
        f"**Why:** {step.detail}",
        "",
        f"**To have it adopted:** {remedy} io looks again on its next scan.",
    ])


# -- what the owner last saw -----------------------------------------------------------


@dataclass(frozen=True)
class AdoptedExternalPullRequest:
    """One open PR carrying the origin label, as the board shows it."""

    pr_number: int
    #: The issue it references; None once an edit removed the reference (it
    #: is then refused, and no lane acts on it).
    issue_number: int | None
    pr_url: str


@dataclass
class ExternalPullRequestLedger:
    """What the adoption owner saw on its last COMPLETE scan, for the board and
    the lanes between scans.

    In memory, like the queues beside it: the first scan after a restart
    rebuilds it from GitHub. Only a complete listing replaces it, so a read
    that failed part-way never drops a PR from the board. ``reported`` holds,
    per PR, the :func:`refusal_marker` of the refusal its comment was SEEN on
    the PR to carry - acknowledged only after the remote write, never when it
    is planned, so a failed write is planned again. ``reviewed_heads``
    memoizes the heads whose review receipt was found, so the routing does not
    re-read it each pass; the receipt on the PR is the record, and every
    write re-reads it.
    """

    adopted: dict[int, AdoptedExternalPullRequest] = field(default_factory=dict)
    reported: dict[int, str] = field(default_factory=dict)
    #: Per issue: the open PRs that are io's own or adopted attempts at it.
    attempts: dict[int, frozenset[int]] = field(default_factory=dict)
    reviewed_heads: dict[int, str] = field(default_factory=dict)

    def adopted_pr_numbers(self) -> frozenset[int]:
        return frozenset(self.adopted)

    def attempts_at(self, issue_number: int) -> frozenset[int]:
        return self.attempts.get(issue_number, frozenset())

    def reviewed_head_known(self, pr_number: int, head_sha: str) -> bool:
        return self.reviewed_heads.get(pr_number) == head_sha

    def remember_reviewed_head(self, pr_number: int, head_sha: str) -> None:
        """A receipt for exactly this head was found on the PR."""
        self.reviewed_heads[pr_number] = head_sha

    def record_scan(
        self,
        adopted: Iterable[AdoptedExternalPullRequest],
        refused: Iterable[ReportRefusedExternalPullRequest],
        attempts: Mapping[int, frozenset[int]],
    ) -> tuple[ReportRefusedExternalPullRequest, ...]:
        """Replace the view with one complete scan; return the refusals not yet
        acknowledged (a PR no longer refused that way is forgotten)."""
        self.adopted = {item.pr_number: item for item in adopted}
        self.attempts = dict(attempts)
        self.reviewed_heads = {number: head for number, head in self.reviewed_heads.items() if number in self.adopted}
        refusals = {step.pr_number: step for step in refused}
        self.reported = {
            number: marker for number, marker in self.reported.items()
            if number in refusals and refusal_marker(refusals[number]) == marker
        }
        return tuple(step for number, step in sorted(refusals.items()) if number not in self.reported)

    def acknowledge(self, step: ReportRefusedExternalPullRequest) -> None:
        """*step*'s report was seen on the PR: it is not told again."""
        self.reported[step.pr_number] = refusal_marker(step)


